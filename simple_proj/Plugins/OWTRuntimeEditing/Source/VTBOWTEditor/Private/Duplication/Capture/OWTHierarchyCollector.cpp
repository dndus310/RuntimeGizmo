#include "Duplication/Capture/OWTHierarchyCollector.h"

#include "Components/ChildActorComponent.h"
#include "Duplication/Capture/OWTSourceValidator.h"
#include "Duplication/OWTDuplicationRequest.h"
#include "Duplication/Pipeline/OWTAdapterDispatcher.h"
#include "GameFramework/Actor.h"

FOWTHierarchyCollector::FOWTHierarchyCollector(AActor& InSource, const FOWTDuplicationContext& InContext)
    : Source(InSource), Context(InContext), Actors(), Visited(), Visiting()
{
}

bool FOWTHierarchyCollector::Collect()
{
	return CollectActor(&Source, false);
}

bool FOWTHierarchyCollector::CaptureAdapterSubjects()
{
	bool bCaptured = true;
	for (AActor* Actor : Actors)
	{
		for (UObject* Subject : GetAdapterSubjects(*Actor))
		{
			bCaptured = bCaptured && Context.Adapters.CaptureSubject(*Subject, Context.Error);
		}
	}
	return bCaptured;
}

const TArray<AActor*>& FOWTHierarchyCollector::GetActors() const
{
	return Actors;
}

TArray<AActor*> FOWTHierarchyCollector::GetRootActors() const
{
	TArray<AActor*> Roots;
	for (AActor* Actor : Actors)
	{
		const UChildActorComponent* Parent = Actor->GetParentComponent();
		const bool bRecreatedByParent = Parent && Visited.Contains(Parent->GetOwner());
		if (!bRecreatedByParent)
		{
			Roots.Add(Actor);
		}
	}
	return Roots;
}

bool FOWTHierarchyCollector::CollectActor(AActor* Actor, bool bManagedChild)
{
	const bool bCycle = Visiting.Contains(Actor);
	const bool bAlreadyCollected = !bCycle && Visited.Contains(Actor);
	if (bCycle)
	{
		Context.Error = TEXT("The authored hierarchy contains an attachment cycle.");
	}

	bool bCollected = !bCycle;
	if (!bCycle && !bAlreadyCollected)
	{
		bCollected = ValidateActor(Actor, bManagedChild);
		if (bCollected)
		{
			Visiting.Add(Actor);
			Visited.Add(Actor);
			Actors.Add(Actor);
			const bool bIncludeAttached = Context.Options.HierarchyScope == EOWTDuplicationHierarchyScope::AuthoredHierarchy;
			bCollected = CollectChildActors(*Actor) && (!bIncludeAttached || CollectAttachedActors(*Actor));
			Visiting.Remove(Actor);
		}
	}
	return bCollected;
}

bool FOWTHierarchyCollector::ValidateActor(AActor* Actor, bool bManagedChild) const
{
	const bool bValidSource =
	    FOWTSourceValidator::ValidateActor(Actor, Context.World, bManagedChild, Context.SourceRules, Context.Error);
	const bool bSameLevel = bValidSource && Actor->GetLevel() == Source.GetLevel();
	const bool bAuthored = bSameLevel && !Context.Adapters.IsManagedObject(*Actor);
	if (bValidSource && !bSameLevel)
	{
		Context.Error = TEXT("An authored descendant belongs to another level.");
	}
	else if (bSameLevel && !bAuthored)
	{
		Context.Error =
		    FString::Printf(TEXT("%s is a managed output, not an authored duplication source."), *Actor->GetPathName());
	}

	bool bAccepted = bAuthored;
	if (bAuthored)
	{
		for (UObject* Subject : GetAdapterSubjects(*Actor))
		{
			bAccepted = bAccepted && Context.Adapters.ValidateSubject(*Subject, Context.Error);
		}
	}
	return bAccepted;
}

bool FOWTHierarchyCollector::CollectChildActors(AActor& Actor)
{
	bool bCollected = true;
	TInlineComponentArray<UChildActorComponent*> Children(&Actor);
	for (UChildActorComponent* Child : Children)
	{
		AActor* ChildActor = Child->GetChildActor();
		bCollected = bCollected && (!ChildActor || CollectActor(ChildActor, true));
	}
	return bCollected;
}

bool FOWTHierarchyCollector::CollectAttachedActors(AActor& Actor)
{
	TArray<AActor*> AttachedActors;
	Actor.GetAttachedActors(AttachedActors, true, false);
	bool bCollected = true;
	for (AActor* Child : AttachedActors)
	{
		// Managed outputs are regenerated by their adapter, so only their attachments are checked.
		const bool bManaged = Context.Adapters.IsManagedObject(*Child);
		bCollected = bCollected && (bManaged ? ValidateManagedDescendants(*Child) : CollectActor(Child, Child->IsChildActor()));
	}
	return bCollected;
}

bool FOWTHierarchyCollector::ValidateManagedDescendants(AActor& ManagedActor) const
{
	TArray<AActor*> Descendants;
	ManagedActor.GetAttachedActors(Descendants, true, true);
	const bool bAllManaged = !Descendants.ContainsByPredicate([this](const AActor* Descendant)
	{
		return !Context.Adapters.IsManagedObject(*Descendant);
	});
	if (!bAllManaged)
	{
		Context.Error = TEXT("An authored Actor is attached beneath a managed output; a logical "
		                     "attachment adapter is required.");
	}
	return bAllManaged;
}

TArray<UObject*> FOWTHierarchyCollector::GetAdapterSubjects(AActor& Actor) const
{
	TArray<UObject*> Subjects;
	Subjects.Add(&Actor);
	TInlineComponentArray<UActorComponent*> Components(&Actor);
	for (UActorComponent* Component : Components)
	{
		if (!Context.Adapters.IsManagedObject(*Component))
		{
			Subjects.Add(Component);
		}
	}
	return Subjects;
}
